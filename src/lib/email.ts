export type ResendEmailInput = {
  to: string;
  subject: string;
  html: string;
  text?: string;
  idempotencyKey?: string;
};

export type ResendEmailResult = {
  delivered: boolean;
  id?: string;
  destination: "resend";
  status: number;
};

export class EmailConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "EmailConfigError";
  }
}

export class EmailSendError extends Error {
  constructor(
    message: string,
    public status: number,
    public details?: unknown,
  ) {
    super(message);
    this.name = "EmailSendError";
  }
}

const defaultTestRecipient = "delivered@resend.dev";

function getEnvValue(env: Record<string, string | undefined>, key: string) {
  const value = env[key]?.trim();
  return value && value.length > 0 ? value : undefined;
}

export function isEmailAddress(value: string) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}

export function formatResendFrom(fromEmail: string) {
  if (fromEmail.includes("<")) return fromEmail;
  return `Private Lab Test <${fromEmail}>`;
}

export function getResendConfigStatus(env: Record<string, string | undefined> = process.env) {
  const apiKey = getEnvValue(env, "RESEND_API_KEY");
  const fromEmail = getEnvValue(env, "RESEND_FROM_EMAIL");
  const testRecipient = getEnvValue(env, "RESEND_TEST_RECIPIENT");

  return {
    configured: Boolean(apiKey && fromEmail),
    hasApiKey: Boolean(apiKey),
    hasFromEmail: Boolean(fromEmail),
    fromEmail: fromEmail ? formatResendFrom(fromEmail) : undefined,
    testRecipient: testRecipient && isEmailAddress(testRecipient) ? testRecipient : defaultTestRecipient,
  };
}

export function resolveEmailTestRecipient(requestedRecipient?: string, env: Record<string, string | undefined> = process.env) {
  const configuredRecipient = getEnvValue(env, "RESEND_TEST_RECIPIENT");

  if (configuredRecipient && isEmailAddress(configuredRecipient)) {
    return configuredRecipient;
  }

  if (env.EMAIL_TEST_ALLOW_CUSTOM_TO === "enabled" && requestedRecipient && isEmailAddress(requestedRecipient)) {
    return requestedRecipient;
  }

  return defaultTestRecipient;
}


export async function sendResendEmail(
  input: ResendEmailInput,
  env: Record<string, string | undefined> = process.env,
  fetcher: typeof fetch = fetch,
): Promise<ResendEmailResult> {
  const apiKey = getEnvValue(env, "RESEND_API_KEY");
  const fromEmail = getEnvValue(env, "RESEND_FROM_EMAIL");

  if (!apiKey) {
    throw new EmailConfigError("RESEND_API_KEY is not configured.");
  }

  if (!fromEmail) {
    throw new EmailConfigError("RESEND_FROM_EMAIL is not configured.");
  }

  const response = await fetcher("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
      ...(input.idempotencyKey ? { "Idempotency-Key": input.idempotencyKey } : {}),
    },
    body: JSON.stringify({
      from: formatResendFrom(fromEmail),
      to: input.to,
      subject: input.subject,
      html: input.html,
      text: input.text,
    }),
  });
  const body = (await response.json().catch(() => ({}))) as { id?: string; message?: string; error?: { message?: string } };

  if (!response.ok) {
    throw new EmailSendError(body.error?.message || body.message || "Resend email send failed.", response.status, body);
  }

  return {
    delivered: true,
    id: body.id,
    destination: "resend",
    status: response.status,
  };
}
